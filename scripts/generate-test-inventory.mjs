#!/usr/bin/env node
/**
 * Regenerates docs/TEST_INVENTORY.md straight from the test files themselves — describe/it/test
 * titles, grouped by file, with a total count. Never hand-edit that file; run this instead.
 *
 * This is a lightweight line-based parser, not a TS AST — it's a small, consistently-formatted
 * test suite, so a regex pass is enough. It expects the repo's own two-space-indent convention.
 *
 * `npm run docs:test-inventory` regenerates. No CI enforcement right now — GitHub Actions isn't
 * available in this environment (every run fails before a runner is even assigned; not a content
 * problem, confirmed by comparing raw committed bytes directly). Re-run this by hand after adding
 * or renaming a test; same idea as `contract/check-contract-drift.mjs`, just not automated for now.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

const LAYERS = [
  { dir: 'api', label: 'API / integration — `api/` (Vitest + native `fetch`)' },
  { dir: 'e2e', label: 'Web — `e2e/` (Playwright)' },
  {
    dir: 'prodcheck',
    label:
      'Production mode (opt-in, NOT part of `npm run test:api`) — `prodcheck/` (Vitest, ' +
      '`npm run test:prodmode` after `npm run prodcheck:up` — see docker-compose.prodcheck.yml)',
  },
];

function specFiles(dir) {
  return readdirSync(path.join(repoRoot, dir))
    .filter((f) => f.endsWith('.spec.ts'))
    .sort();
}

function parseFile(filePath) {
  // Whole-file, not line-by-line: titles sometimes start on the line after `it(`/`test(` (long
  // titles built with string concatenation, e.g. api/13-proxy.spec.ts) — \s already matches
  // newlines, but only if the call and its title are matched as one span rather than per-line.
  const text = readFileSync(filePath, 'utf8');
  const groups = []; // { describe, tests: [{title, parametrized}] }
  let current = { describe: null, tests: [] };

  // One combined pass over the file, in source order, so tests land under the describe block
  // that actually precedes them.
  const blockRe = /\b(describe|it|test)(\.each\([^)]*\))?\(\s*(['"`])((?:\\.|(?!\3)[^\\])*)\3/g;
  const concatRe = /^\s*\+\s*(['"`])((?:\\.|(?!\1)[^\\])*)\1/;
  let m;
  while ((m = blockRe.exec(text))) {
    const [, kind, eachCall, , firstPart] = m;
    // Titles built as `'a' + 'b' + 'c'` (long explanatory test names in this suite) — keep
    // consuming `+ '...'` continuations right after the match so the inventory shows the real,
    // complete title instead of just its first fragment.
    let title = firstPart;
    let rest = text.slice(blockRe.lastIndex);
    let c;
    while ((c = rest.match(concatRe))) {
      title += c[2];
      const consumed = c[0].length;
      blockRe.lastIndex += consumed;
      rest = rest.slice(consumed);
    }
    // Unescape \' \" \` — the source escapes them for JS, but this doc renders as prose.
    title = title.replace(/\\(['"`])/g, '$1');
    if (kind === 'describe') {
      if (current.describe !== null || current.tests.length) groups.push(current);
      current = { describe: title, tests: [] };
    } else {
      current.tests.push({ title, parametrized: !!eachCall });
    }
  }
  if (current.describe !== null || current.tests.length) groups.push(current);
  return groups;
}

let body = '';
let totalBlocks = 0;

for (const layer of LAYERS) {
  body += `\n## ${layer.label}\n`;
  for (const file of specFiles(layer.dir)) {
    const filePath = path.join(repoRoot, layer.dir, file);
    const groups = parseFile(filePath);
    const fileTotal = groups.reduce((n, g) => n + g.tests.length, 0);
    totalBlocks += fileTotal;
    body += `\n### \`${layer.dir}/${file}\` (${fileTotal} declared block${fileTotal === 1 ? '' : 's'})\n`;
    for (const g of groups) {
      if (!g.tests.length) continue;
      if (g.describe) body += `\n**${g.describe}**\n`;
      for (const t of g.tests) {
        const suffix = t.parametrized ? ' _(parametrized — one row per case, see source)_' : '';
        body += `- ${t.title}${suffix}\n`;
      }
    }
  }
}

const header = `# Test Inventory

Auto-generated by \`npm run docs:test-inventory\` (${path.relative(repoRoot, fileURLToPath(import.meta.url)).replace(/\\/g, '/')}) — do not hand-edit. Regenerate after adding or renaming any test.

Not auto-enforced by CI right now (GitHub Actions isn't available in this environment) — regenerate by hand with the command above after adding or renaming a test.

**${totalBlocks} declared test blocks** across ${LAYERS.length} layers as of the last generation. Parametrized blocks (\`it.each\`) count once here but expand to multiple cases at run time — the real per-run totals (e.g. 37 API / 11 E2E) come from an actual test run, not this count; see the latest report under [reports/](../reports/).
`;

const outPath = path.join(repoRoot, 'docs', 'TEST_INVENTORY.md');
writeFileSync(outPath, header + body);
console.log(`✅ Wrote ${path.relative(repoRoot, outPath)} (${totalBlocks} declared test blocks)`);
